@doc """
    otf(sampled_otf, wh)
    otf(sampled_otf, img)

Generate an otf array for the given transfer function with the size `wh` (size of `img`) and with a pixel distance of `Δxy`

!!! note
    The pixel size/distance (`Δxy`) is required for a [model transfer function](@ref ModelTransferFunction) and optional
    for a [`MeasuredTransferFunction`](@ref). If the pixel size/distance is not supplied to the
    [`MeasuerdTransferFunction`](@ref), it is assumed to be the same as in the measurement.

# Arguments
* `tf::TransferFunction`: transfer function (model/measured) to generate the OTF for
* `wh::Tuple{Integer, Integer}` or `wh::Integer`: (width, height) of the generated OTF. `wh` ↦ `(wh, wh)` if `wh isa
    Integer`.
* `Δxy::Tuple{Length, Length}` or `Δxy::Length`: Separation of pixels in the ``x`` and ``y`` dimensions of the generated
    OTF image. `Δxy` ↦ `(Δxy, Δxy)` if `Δxy isa Length`. (default: pixel distance from the measurement for a 
    [`MeasuredTransferFunction`](@ref))
* `δ::Tuple = (0,0)`: shift of the OTF in the image plane in pixels. This is useful for some algorithms, e.g. in 
    structured illumination microscopy reconstruction algorithms.
"""
# TODO: This should be shifted for a PSF that is real <15-09-23> 
function otf(
    tf::SampledOTF{N},
    wh::Indices{N}
) where {N}
    # TODO: This should instead be generated by a util function <26-08-24> 
    fxs, fys = ndgrid(fftfreq(wh[1], 1 / tf.Δxy[1]), fftfreq(wh[2], 1 / tf.Δxy[2]))
    # PERF: Could be speeded up using `ShiftedArrays` with integer `δ` <20-07-23> 
    return otf.(tf,
        fxs .- tf.center[1] / (tf.Δxy[1] * wh[1]),
        fys .- tf.center[2] / (tf.Δxy[2] * wh[2]))
end



