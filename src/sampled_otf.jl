struct SampledOTF{N}
    "physical illumination pattern"
    transfer::OpticalTransferFunction{N}
    "pixel dimensions"
    Δxy::PixelSize{N}
    "center coordinate of the sample (useful for modulation methods such as SIM.)"
    center::Coordinate{N}
end

# NOTE: step 1 - fill in the pixel-size
SampledOTF(tf::OpticalTransferFunction{N}, Δxy::Length, args...) where {N} = SampledOTF(tf, fillsize(Δxy, N), args...)
# NOTE: step 2 - default center (ones)
SampledOTF(tf::OpticalTransferFunction{N}, Δxy::PixelSize{N}) where {N} = SampledOTF(tf, Δxy, ntuple(_ -> 1, Val(N)))

